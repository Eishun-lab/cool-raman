// 🎲 均等サンプリング関数（4スキル×4ステージ＝完全16問ブレなし抽出）
// ======================================================================
export function sampleLevelCheckQuestions(): LevelCheckQuestion[] {
  const categories: SkillCategory[] = ['listening', 'reading', 'vocab', 'grammar'];
  const stages: StageLevel[] = [1, 2, 3, 4];
  const selected: LevelCheckQuestion[] = [];

  // 各ステージ × 各スキル から 1問ずつ選出（計16問）
  stages.forEach((stg) => {
    categories.forEach((cat) => {
      const candidates = LEVEL_CHECK_POOL.filter(
        (q) => q.stage === stg && q.category === cat
      );
      if (candidates.length > 0) {
        const randomIndex = Math.floor(Math.random() * candidates.length);
        selected.push(candidates[randomIndex]);
      }
    });
  });

  // 16問をランダムな出題順にシャッフル（ただしリスニングが連続しすぎないように適度に分散）
  return shuffleArray(selected);
}

function shuffleArray<T>(array: T[]): T[] {
  const result = [...array];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
